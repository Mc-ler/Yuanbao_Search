"""Pre-generated demo research: exact-match reuse of prepared plans + results.

Three demo questions (examples/q1..q3) are pre-generated by
scripts/prepare_demos.py into demos/<example_id>.json. match_demo returns a
prepared payload by exact example_id, then by normalized question text.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
DEMOS_DIR = ROOT / "demos"


def _normalize(text: str) -> str:
    return re.sub(r"\s+", "", (text or "")).strip().lower()


def demo_path(example_id: str) -> Path:
    return DEMOS_DIR / f"{example_id}.json"


def load_demo(example_id: str) -> dict[str, Any] | None:
    path = demo_path(example_id)
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return data if isinstance(data, dict) else None


def save_demo(example_id: str, payload: dict[str, Any]) -> Path:
    DEMOS_DIR.mkdir(parents=True, exist_ok=True)
    path = demo_path(example_id)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def match_demo(question: str = "", example_id: str = "") -> dict[str, Any] | None:
    """Exact-match a prepared demo by example_id, then by normalized question."""
    if example_id:
        demo = load_demo(example_id)
        if demo is not None:
            return demo
    if question:
        target = _normalize(question)
        if target:
            for path in sorted(DEMOS_DIR.glob("*.json")):
                demo = load_demo(path.stem)
                if demo is None:
                    continue
                if _normalize(str(demo.get("question") or "")) == target:
                    return demo
    return None
